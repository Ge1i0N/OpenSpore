"""Generate source/engine/typeids.inc from the upstream type registry.

Why: a decoded resource is still opaque while its type shows as `type=0x024a0e52`. The
registry `upstream/SporeMaster3/data/reg_type.txt` maps an extension/name to a type id, and
that registry is a *name table*, not a hash scheme (type ids are assigned, not FNV of the name
- see IDEAS.md §5.20). Embedding it lets the reader print names without a runtime file
dependency, and the .inc is regenerated by this tool so it stays traceable to its source.

Usage: python tools/gen_typeids.py
Writes: source/engine/typeids.inc
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "upstream" / "SporeMaster3" / "data" / "reg_type.txt"
DST = ROOT / "source" / "engine" / "typeids.inc"


def main() -> int:
    if not SRC.is_file():
        print(f"! missing {SRC}")
        return 1
    rows: dict[int, str] = {}
    conflicts = 0
    for line in SRC.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        name = parts[0].strip()
        hexv = parts[1].strip()
        if not hexv.lower().startswith("0x"):
            continue
        try:
            tid = int(hexv, 16)
        except ValueError:
            continue
        if tid in rows and rows[tid] != name:
            conflicts += 1
            continue  # first wins; aliases are expected
        rows[tid] = name
    items = sorted(rows.items())
    out = [
        "// GENERATED by tools/gen_typeids.py from upstream/SporeMaster3/data/reg_type.txt",
        "// Do not edit by hand. Regenerate with: python tools/gen_typeids.py",
        "//",
        f"// {len(items)} type ids ({conflicts} duplicate-id aliases skipped, first name kept).",
        "// Type ids are assigned by the game, NOT derived from the name by any FNV variant",
        "// (tested 0/6 in IDEAS.md section 5.20), so this table is the practical name source.",
        "#pragma once",
        "#include \"common.h\"",
        "",
        "namespace os::pkg {",
        "",
        "struct TypeIdName {",
        "    u32 id;",
        "    const char* name;",
        "};",
        "",
        "// Sorted by id for binary search.",
        "inline constexpr TypeIdName kTypeIds[] = {",
    ]
    for tid, name in items:
        out.append(f'    {{0x{tid:08x}u, "{name}"}},')
    out.append("};")
    out.append("")
    out.append("inline constexpr u32 kTypeIdCount = sizeof(kTypeIds) / sizeof(kTypeIds[0]);")
    out.append("")
    out.append("inline const char* type_id_name(u32 id) {")
    out.append("    u32 lo = 0, hi = kTypeIdCount;")
    out.append("    while (lo < hi) {")
    out.append("        const u32 mid = (lo + hi) / 2;")
    out.append("        if (kTypeIds[mid].id < id) lo = mid + 1;")
    out.append("        else hi = mid;")
    out.append("    }")
    out.append("    return (lo < kTypeIdCount && kTypeIds[lo].id == id) ? kTypeIds[lo].name : nullptr;")
    out.append("}")
    out.append("")
    out.append("}  // namespace os::pkg")
    out.append("")
    DST.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}: {len(items)} ids, {conflicts} duplicate-id aliases skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
