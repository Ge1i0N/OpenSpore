r"""Function inventory + reversal coverage for the GA oracle.

Why this exists: a "function map" (how much of the ENGINE's code we have reversed) needs a
denominator. This tool derives one from the oracle itself, without a PDB, because the beta PDB is
a DIFFERENT link (0/12 addresses match the GA target - analysis/build_identity.md), so its
addresses are not usable as the oracle's.

Denominator: candidate function starts in .text, taken as the union of
  * every E8/E9 rel32 target that lands inside .text (calls and tail jumps),
  * every 4-byte pointer in .rdata/.data that points into .text (vtables, function tables),
  * classic prologues: 55 8B EC (push ebp; mov ebp,esp) and 8B FF (mov edi,edi hotpatch).
That over-counts slightly (a jump into the middle of a function counts as a "start"), which is
fine for a coverage figure and is stated as such.

Numerator: the functions we have actually reversed/named, kept in analysis/functions_named.json
(address -> name + what we learned). Names can also come from the beta PDB where identity matches,
but that is a separate, larger effort.

Usage: python tools/functions.py
"""
from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

NAMED = ROOT / "analysis" / "functions_named.json"


def candidate_starts(pe) -> set[int]:
    text = pe.sections[".text"]
    t0, t1 = text["va"], text["end_va"]
    blob = pe.section_bytes(".text")
    starts: set[int] = set()

    # E8/E9 rel32 targets inside .text
    for i in range(len(blob) - 5):
        op = blob[i]
        if op != 0xE8 and op != 0xE9:
            continue
        rel = struct.unpack("<i", blob[i + 1 : i + 5])[0]
        tgt = t0 + i + 5 + rel
        if t0 <= tgt < t1:
            starts.add(tgt)

    # pointers into .text from .rdata/.data
    for sec in (".rdata", ".data"):
        if sec not in pe.sections:
            continue
        data = pe.section_bytes(sec)
        sva = pe.sections[sec]["va"]
        for i in range(0, len(data) - 4, 4):
            v = struct.unpack("<I", data[i : i + 4])[0]
            if t0 <= v < t1:
                starts.add(v)

    # prologues
    for i in range(len(blob) - 3):
        if blob[i] == 0x55 and blob[i + 1] == 0x8B and blob[i + 2] == 0xEC:
            starts.add(t0 + i)
        elif blob[i] == 0x8B and blob[i + 1] == 0xFF:
            starts.add(t0 + i)

    return starts


def main() -> int:
    from tools.pe import PE

    pe = PE()
    starts = candidate_starts(pe)
    named = json.loads(NAMED.read_text(encoding="utf-8")) if NAMED.exists() else {}
    named_addrs = {int(k, 16) for k in named}
    hit = len(named_addrs & starts)
    cov = 100.0 * hit / len(starts) if starts else 0.0

    print(f"# oracle: {pe.path.name}")
    print(f"candidate function starts in .text : {len(starts):,}")
    print(f"functions we have reversed/named   : {len(named):,}")
    print(f"  ... that land on a candidate start: {hit:,}")
    print(f"coverage (named / candidates)      : {cov:.3f}%")
    print()

    from collections import Counter
    by_area = Counter(v.get("area", "?") for v in named.values())
    print("By area (named counts):")
    for k, n in sorted(by_area.items(), key=lambda x: -x[1]):
        print(f"  {k:<24} {n}")

    # machine-readable stats for the progress map
    stats = {
        "oracle": pe.path.name,
        "candidate_starts": len(starts),
        "named": len(named),
        "named_on_candidate": hit,
        "coverage_pct": round(cov, 4),
        "by_area": dict(by_area),
        "denominator_note": "candidate starts = union of E8/E9 rel32 targets in .text, .rdata/.data "
                            "pointers into .text, and prologues (55 8B EC / 8B FF). An upper bound: "
                            "a jump into a function body also counts.",
    }
    (ROOT / "analysis" / "functions_stats.json").write_text(
        json.dumps(stats, indent=2) + "\n", encoding="utf-8")

    lines = [
        "# Function map — how much of the oracle's CODE is reversed",
        "",
        "> Generated by `tools/functions.py`. The DENOMINATOR is the oracle's own `.text`, not the",
        "> beta PDB: that PDB is a different link (0/12 addresses match — `analysis/build_identity.md`),",
        "> so it can supply NAMES but not addresses. The NUMERATOR is `analysis/functions_named.json`",
        "> (functions we have actually reversed/named).",
        "",
        f"**{len(starts):,}** candidate function starts in `.text` (upper bound; see the tool's note) ·",
        f"**{len(named)}** functions reversed/named · **{cov:.3f}%** coverage.",
        "",
        "This is deliberately a HARD number, and it is small. It is not in tension with the feature",
        "map's high engine figure: the feature map measures the scope we chose (boot chain + asset",
        "formats), whereas this measures the whole binary's code, of which the engine's 100k+ functions",
        "are barely touched. Both are true; together they are the honest picture.",
        "",
        "## Reversed/named functions by area",
        "",
        "| area | count |",
        "|---|---|",
    ]
    for k, n in sorted(by_area.items(), key=lambda x: -x[1]):
        lines.append(f"| {k} | {n} |")
    lines += ["", "## The functions (address · name · what we learned)", "",
              "| address | name | area | note |", "|---|---|---|---|"]
    for addr in sorted(named, key=lambda a: int(a, 16)):
        v = named[addr]
        lines.append(f"| `{addr}` | {v.get('name','?')} | {v.get('area','')} | {v.get('note','')} |")
    lines.append("")

    # If the PDB symbol map exists, show the engine's SHAPE (names by subsystem) next to our count.
    pdb = ROOT / "analysis" / "pdb_symbols.json"
    if pdb.exists():
        ps = json.loads(pdb.read_text(encoding="utf-8"))
        lines += [
            "## The engine's shape, from the beta PDB (names only, not addresses)",
            "",
            f"The beta PDB carries **{ps['unique_functions']:,}** unique function/method name paths. The",
            "PDB is a different link, so these are NAMES, not addresses — but they are the engine's own",
            "vocabulary and they say what the code is made of. Largest subsystems:",
            "",
            "| subsystem | functions |",
            "|---|---|",
        ]
        for k, n in ps["namespaces"][:16]:
            lines.append(f"| {k} | {n:,} |")
        lines += ["", "Full breakdown: `analysis/pdb_symbols.md`.", ""]
    lines += [
        "## Address guesses (partial)",
        "",
        "A full PDB-name→address map is not derivable (no beta binary, no matching reference build,",
        "RTTI off). `tools/name_guess.py` still produces a ranked GUESS list by matching strings an",
        "oracle function references against PDB name tokens — see `analysis/name_guesses.md`.",
        "",
    ]
    (ROOT / "analysis" / "functions.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote analysis/functions.md and analysis/functions_stats.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
