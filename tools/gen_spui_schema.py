"""Generate source/engine/spui_schema.inc from the SHIPPED Spore UI Designer XML.

Same pattern as tools/gen_typeids.py -> typeids.inc: the registry is DATA, so the table is generated
at build time from the shipped files rather than typed by hand, and the generator records where the
facts came from.

Source: the 14 `xml` resources (type 0xCF6C21B8) inside the shipped packages, extracted verbatim to
analysis/scripts/xml/ by this session. They are the Spore UI Designer's own project files, and their
<Class>/<Property> elements carry `proxy` ids - the dictionary that makes `spui` readable.

Emitted per id: the name, the schema type, the code the BINARIES use for that property (measured, see
tools/spui_typecode.py: the u16 after the id is a TYPE CODE stable per id, 94.5% of high ids having
exactly one), and the payload size that code implies (measured by majority vote in tools/spui_read.py).
The code/size are what a reader needs; the type is what a human needs to interpret the bytes.
"""
import os
import re
import glob
import json
import struct
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "source", "engine", "spui_schema.inc")

# The measured code -> payload size table (tools/spui_read.py, majority vote over 748 layouts).
# 18 is the string form (a u16 char count then UTF-16) and 19 an array count; both are variable, so
# the size column carries the FIXED part only and the reader adds the counted bytes.
CODE_SIZE = {3: 1, 5: 4, 7: 7, 9: 4, 11: 4, 16: 16, 17: 8, 19: 2, 20: 6, 18: 0, 2: 0}
CODE_VARIABLE = {18, 2}


def harvest(xml_dir):
    """Every <Class> and <Property> with a proxy id, from the shipped designer files."""
    props, classes = {}, {}
    for path in sorted(glob.glob(os.path.join(xml_dir, "*.xml"))):
        txt = open(path, encoding="utf-8", errors="replace").read()
        for m in re.finditer(r"<(Class|Property)\b([^>]*)>", txt):
            kind, attrs = m.group(1), m.group(2)
            pm = re.search(r'proxy="(0x[0-9A-Fa-f]{1,8})"', attrs)
            if not pm:
                continue
            nm = re.search(r'name="([^"]*)"', attrs)
            ty = re.search(r'type="([^"]*)"', attrs)
            df = re.search(r'default="([^"]*)"', attrs)
            base = re.search(r'base="([^"]*)"', attrs)
            rec = {
                "name": (nm.group(1) if nm else "?").strip(),
                "type": (ty.group(1) if ty else "").strip(),
                "default": (df.group(1) if df else "").strip(),
                "base": (base.group(1) if base else "").strip(),
            }
            v = int(pm.group(1), 16)
            (classes if kind == "Class" else props).setdefault(v, rec)
    return classes, props


def measured_codes(codes_json):
    """id -> (code, count) from tools/spui_typecode.py's output, if it has been run."""
    if not os.path.exists(codes_json):
        return {}
    return json.load(open(codes_json, encoding="utf-8"))


def main():
    xml_dir = os.path.join(ROOT, "analysis", "scripts", "xml")
    classes, props = harvest(xml_dir)
    if not props and not classes:
        print("no designer XML under %s" % xml_dir)
        return 2
    print("harvested: %d Class + %d Property = %d ids" % (len(classes), len(props),
                                                          len(classes) + len(props)))

    codes = measured_codes(os.path.join(ROOT, "analysis", "audit", "spui_codes.json"))
    if codes:
        print("measured codes available for %d ids" % len(codes))
    else:
        print("NOTE: analysis/audit/spui_codes.json absent; emitting names/types only")

    def esc(s):
        return s.replace("\\", "\\\\").replace('"', '\\"')

    lines = [
        "// GENERATED by tools/gen_spui_schema.py from the SHIPPED Spore UI Designer XML.",
        "// Do not edit by hand. Regenerate with: python tools/gen_spui_schema.py",
        "//",
        "// Source: the 14 `xml` resources (type 0xCF6C21B8) inside the shipped packages, extracted",
        "// verbatim to analysis/scripts/xml/. They are EA's own UI designer project files, and their",
        "// <Class>/<Property> `proxy` attributes are the dictionary that makes `spui` readable -",
        "// see analysis/spui-schema.md.",
        "//",
        "// `code` is the u16 the BINARIES place after this id, measured (tools/spui_typecode.py): it is",
        "// a TYPE CODE, stable per id (94.5% of ids >= 0x1000 have exactly one across 748 layouts), not",
        "// a length. `size` is the payload that code implies, by majority vote (tools/spui_read.py).",
        "// A record is  id(4) | code:u16 | marker:u16(==1) | payload(size).  Code 18 is a string (u16",
        "// char count then UTF-16) and 19 an array (u16 element count); both are variable, so their",
        "// size column carries the fixed part only.",
        "//",
        "// The ids below 0x1000 are BLOCK-SCOPED member indices: the same value means different things",
        "// in different structs (0x01 = Size in Outline Format, TextStyle in a text control). They are",
        "// emitted with their names for completeness, but a reader must not treat them as global.",
        "#pragma once",
        '#include "common.h"',
        "",
        "namespace os::spui {",
        "",
        "struct SchemaEntry {",
        "    u32 id;",
        "    const char* name;",
        "    const char* type;      // the designer's own type, e.g. rectf / color / string_resource",
        "    u16 code;              // the measured type code, 0xFFFF when unmeasured",
        "    u16 size;              // the fixed payload size that code implies, 0 when variable",
        "    bool is_class;         // true for <Class> (a node type), false for <Property>",
        "    bool block_scoped;     // true when id < 0x1000: a member index, not a global key",
        "};",
        "",
        "static const SchemaEntry kSchema[] = {",
    ]
    allids = sorted(set(list(classes.keys()) + list(props.keys())))
    for v in allids:
        rec = classes.get(v) or props.get(v)
        is_class = v in classes
        code, size = 0xFFFF, 0
        if codes and str(v) in codes:
            c = codes[str(v)]
            code = c.get("code", 0xFFFF)
            size = CODE_SIZE.get(code, 0)
        lines.append('    {0x%08Xu, "%s", "%s", %uu, %uu, %s, %s},'
                     % (v, esc(rec["name"])[:60], esc(rec["type"])[:28],
                        code if code != 0xFFFF else 0xFFFF, size,
                        "true" if is_class else "false",
                        "true" if v < 0x1000 else "false"))
    lines += [
        "};",
        "static const int kSchemaCount = %d;" % len(allids),
        "",
        "// The window-property block UTFWin owns, by name, so the reader can say what it found.",
        "// Measured from the corpus: these ids co-occur in one ordered block per window.",
        "enum WindowProp {",
        "    kWinFlags       = 0xeec1b000u,",
        "    kWinControlID   = 0xeec1b001u,",
        "    kWinCommandID   = 0xeec1b002u,",
        "    kWinShadeColor  = 0xeec1b004u,",
        "    kWinArea        = 0xeec1b005u,   // rectf: x, y, w, h as four floats",
        "    kWinBgColor     = 0xeec1b006u,",
        "    kWinDrawable    = 0xeec1b007u,",
        "    kWinCaption     = 0xeec1b00au,   // code 18: inline UTF-16 OR a locale TABLE reference",
        "    kWinChildren    = 0xeec1b00bu,",
        "    kWinProcs       = 0xeec1b00cu,",
        "    kWinTextFont    = 0xeec1b00eu,",
        "};",
        "",
        "}  // namespace os::spui",
    ]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d entries)" % (OUT, len(allids)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
