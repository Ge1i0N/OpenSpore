r"""PDB symbol/name map - the engine's own function vocabulary.

Why this exists: the GA oracle's .text is encrypted, and the beta PDB is a DIFFERENT link
(0/12 addresses match the target - analysis/build_identity.md), so PDB ADDRESSES are unusable.
But the PDB is NOT stripped: it carries ~194k unique MSVC-mangled names. Those names are the
engine's own vocabulary (class::method, namespaces, subsystems), which is exactly what makes a
disassembly readable. This tool harvests them and groups them by subsystem.

What it does NOT claim: any address correspondence. Names only.

Method: scan the PDB bytes for `?...@@` mangled runs, keep the name path (everything before the
first `@@`), reverse the `@`-separated components into `Namespace::Class::Method`, and bucket by
the outermost namespace. Template names (`?$...`) are counted separately (they are mostly types).

Usage: python tools/pdb_symbols.py                 # writes analysis/pdb_symbols.md + .json
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

PDB = ROOT / "refs" / "bins" / "Beta190208" / "SporeApp.pdb"
# MSVC decorated names: start with '?', run to the terminator. We only need the name path.
MANGLED = re.compile(rb"\?[A-Za-z0-9_@?$<>:.\-]{4,}")


def name_path(m: bytes) -> str | None:
    """`?Method@Class@NS@@...` -> `NS::Class::Method`. Templates/specials -> None."""
    s = m.decode("latin-1", "replace")
    if s.startswith("?$"):          # template name, not a plain function path
        return None
    if s.startswith("?") is False:
        return None
    # split at the end of the name path
    if "@@" not in s:
        return None
    path = s[1:].split("@@", 1)[0]
    comps = [c for c in path.split("@") if c]
    if not comps:
        return None
    return "::".join(reversed(comps))


def main() -> int:
    if not PDB.exists():
        print(f"no PDB at {PDB}")
        return 1
    data = PDB.read_bytes()
    print(f"# {PDB.name}  {len(data):,} bytes")

    raw = MANGLED.findall(data)
    uniq_raw = set(raw)
    paths = [name_path(m) for m in uniq_raw]
    funcs = [p for p in paths if p]
    uniq_funcs = sorted(set(funcs))

    print(f"mangled runs        : {len(raw):,}")
    print(f"unique mangled      : {len(uniq_raw):,}")
    print(f"with a name path    : {len(uniq_funcs):,} unique functions/methods")

    # bucket by outermost scope: the first component of the reversed path (SP, EA, rw, eastl, ...)
    def top_ns(p: str) -> str:
        parts = p.split("::")
        return parts[0] if parts else "?"

    ns = Counter(top_ns(p) for p in uniq_funcs)
    # also bucket by the class (second-to-last component) for the biggest namespaces
    classes = Counter()
    for p in uniq_funcs:
        parts = p.split("::")
        if len(parts) >= 2:
            classes["::".join(parts[-2:])] += 1

    lines = [
        "# PDB symbol map — the engine's function vocabulary",
        "",
        "> Generated by `tools/pdb_symbols.py` from `refs/bins/Beta190208/SporeApp.pdb`.",
        "> The PDB is a **different link** (0/12 addresses match the GA target —",
        "> `analysis/build_identity.md`), so this is a **NAME** inventory, never an address map.",
        "> It is what makes the disassembly readable: the engine's own class::method vocabulary.",
        "",
        f"- unique mangled names in the PDB: **{len(uniq_raw):,}**",
        f"- unique function/method name paths: **{len(uniq_funcs):,}**",
        f"- (template/type names, excluded here: {len(uniq_raw) - len(uniq_funcs):,})",
        "",
        "For comparison, `analysis/functions.md` counts the **oracle's** code (105,239 candidate",
        "starts, 29 reversed). The PDB is the opposite: names without addresses. Together they say",
        "what the engine is made of and how much of it we have read.",
        "",
        "## By outermost namespace (top 40)",
        "",
        "| namespace | functions |",
        "|---|---|",
    ]
    for k, n in ns.most_common(40):
        lines.append(f"| {k} | {n} |")
    lines += ["", "## Largest classes (top 40)", "", "| class::method-prefix | count |", "|---|---|"]
    for k, n in classes.most_common(40):
        lines.append(f"| {k} | {n} |")
    lines += ["", "## Sample names by subsystem", ""]
    for target in ("AppStateManager", "Refpack", "UTFWin", "Renderable2D", "Texture", "RenderWare",
                   "Raster", "DBPF", "Package", "Resource", "Model", "Mesh", "Shader"):
        sample = [p for p in uniq_funcs if target.lower() in p.lower()][:6]
        if sample:
            lines.append(f"**{target}** — {len([p for p in uniq_funcs if target.lower() in p.lower()])} names")
            lines.append("")
            for s in sample:
                lines.append(f"- `{s}`")
            lines.append("")
    (ROOT / "analysis" / "pdb_symbols.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (ROOT / "analysis" / "pdb_symbols.json").write_text(
        json.dumps({"unique_mangled": len(uniq_raw), "unique_functions": len(uniq_funcs),
                    "namespaces": ns.most_common(60), "classes": classes.most_common(60)},
                   indent=2) + "\n", encoding="utf-8")
    # Full name list, for the address guesser (tools/name_guess.py).
    (ROOT / "analysis" / "pdb_names.txt").write_text("\n".join(uniq_funcs) + "\n", encoding="utf-8")
    print("wrote analysis/pdb_symbols.md, analysis/pdb_symbols.json, analysis/pdb_names.txt")
    print("\ntop namespaces:")
    for k, n in ns.most_common(12):
        print(f"  {k:<24} {n}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
