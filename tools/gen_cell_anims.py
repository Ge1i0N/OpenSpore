#!/usr/bin/env python3
"""Generate cell_anims.inc from the xls animation table in CellGame.package.

The xls resource (type 0x1F639D98) is an OLE2/Excel workbook with one sheet
mapping ANIM_EVENT names to clip names, movement styles and speed flags.
This tool extracts that table and emits a C++ include file with the data.
"""
import argparse
import struct
import sys
from pathlib import Path

XLS_TYPE = 0x1F639D98


def find_packages():
    roots = []
    import os
    if "SPORE_DATA" in os.environ:
        roots.append(Path(os.environ["SPORE_DATA"]))
    roots.append(Path("build/bin/Debug/Data"))
    roots.append(Path("build/bin/Debug/DataEP1"))
    for r in roots:
        if r.exists():
            yield r


def iter_resources(pkg_path):
    """Minimal DBPF reader to find the xls resource."""
    data = pkg_path.read_bytes()
    if len(data) < 96:
        return
    # DBPF header
    magic = data[:4]
    if magic not in (b"DBPF", b"DBP2"):
        return
    major = struct.unpack_from("<I", data, 4)[0]
    minor = struct.unpack_from("<I", data, 8)[0]
    index_offset = struct.unpack_from("<I", data, 12)[0]
    index_size = struct.unpack_from("<I", data, 16)[0]
    if index_offset + index_size > len(data):
        return
    idx = data[index_offset:index_offset + index_size]
    # Parse index entries (28 bytes each for kind 4)
    n = len(idx) // 28
    for i in range(n):
        off = i * 28
        if off + 28 > len(idx):
            break
        type_id = struct.unpack_from("<I", idx, off)[0]
        group_id = struct.unpack_from("<I", idx, off + 4)[0]
        instance_id = struct.unpack_from("<I", idx, off + 8)[0]
        offset_val = struct.unpack_from("<I", idx, off + 12)[0]
        size_val = struct.unpack_from("<I", idx, off + 16)[0]
        if type_id == XLS_TYPE:
            yield type_id, group_id, instance_id, data[offset_val:offset_val + size_val]


def parse_xls_sheet(data):
    """Parse OLE2 compound document to extract the first sheet's cell values."""
    try:
        import xlrd
        import io
        book = xlrd.open_workbook(file_contents=data)
        sheet = book.sheet_by_index(0)
        rows = []
        for r in range(sheet.nrows):
            row = []
            for c in range(sheet.ncols):
                v = sheet.cell_value(r, c)
                row.append(v)
            rows.append(row)
        return rows
    except ImportError:
        return None


def parse_anim_rows(rows):
    """Parse animation rows into structured data."""
    anims = []
    for row in rows:
        if len(row) < 2:
            continue
        event = str(row[0]).strip() if row[0] else ""
        clip = str(row[1]).strip() if row[1] else ""
        if not event or not clip:
            continue
        if event.startswith("ANIM_") or event == "":
            style = str(row[2]).strip() if len(row) > 2 and row[2] else ""
            speed = 0.0
            if len(row) > 3 and row[3]:
                try:
                    speed = float(row[3])
                except (ValueError, TypeError):
                    speed = 0.0
            anims.append({
                "event": event,
                "clip": clip,
                "style": style,
                "speed": speed,
            })
    return anims


def generate_inc(anims, output_path):
    """Generate C++ include file with animation data."""
    lines = [
        "// Auto-generated by tools/gen_cell_anims.py from CellGame.package xls resource.",
        "// Do not edit manually.",
        "#pragma once",
        "#include <cstddef>",
        "",
        "namespace os::cell {",
        "",
        "struct AnimationDef {",
        "    const char* event;",
        "    const char* clip;",
        "    const char* style;",
        "    float speed;",
        "};",
        "",
        f"inline constexpr AnimationDef kCellAnims[] = {{",
    ]
    for a in anims:
        event = a["event"].replace('"', '\\"')
        clip = a["clip"].replace('"', '\\"')
        style = a["style"].replace('"', '\\"')
        lines.append(f'    {{"{event}", "{clip}", "{style}", {a["speed"]}f}},')
    lines.append("};")
    lines.append("")
    lines.append(f"inline constexpr size_t kCellAnimCount = {len(anims)};")
    lines.append("")
    lines.append("}  // namespace os::cell")
    lines.append("")
    output_path.write_text("\n".join(lines), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", type=Path, default=Path("source/engine/cell_anims.inc"))
    args = ap.parse_args()

    for pkg_root in find_packages():
        for pkg in sorted(pkg_root.glob("*.package")):
            for type_id, group_id, instance_id, data in iter_resources(pkg):
                if data[:8] == b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1":
                    rows = parse_xls_sheet(data)
                    if rows:
                        anims = parse_anim_rows(rows)
                        if anims:
                            generate_inc(anims, args.output)
                            print(f"Generated {args.output} with {len(anims)} animations from {pkg.name}")
                            return 0
    print("No xls animation table found", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
